# 各维度理论范围（最小，最大）
RANGES = [
    (-100, 104),   # D1
    (-97, 120),    # D2
    (-52, 67),     # D3
    (-35, 40),     # D4
    (-94, 100),    # D5
    (-91, 105),    # D6
    (-111, 124),   # D7
]

def generate_answers():
    """随机生成40个选项（A/B/C/D）"""
    return [random.choice(['A','B','C','D']) for _ in range(40)]

def compute_scores(answers):
    """根据选项和分数表计算七维总分X"""
    scores = [0]*7
    for i, ans in enumerate(answers):
        opt_idx = ord(ans) - ord('A')
        item_scores = SCORES_TABLE[i][opt_idx]
        for d in range(7):
            scores[d] += item_scores[d]
    return scores

def generate_calibrated_scores(x, noise_std=5):
    """
    根据理论分X生成校准后的理论分（与X同量纲）。
    模拟“真实能力” = 理论分 + 随机噪声（可正可负），并裁剪到理论范围。
    这样可以实现“70→80”式的微调效果。
    """
    calibrated = []
    for d in range(7):
        # 添加高斯噪声，标准差 noise_std
        noisy = x[d] + np.random.normal(0, noise_std)
        min_x, max_x = RANGES[d]
        # 裁剪到理论范围
        clipped = max(min_x, min(max_x, noisy))
        # 保留一位小数，使分数更细腻
        calibrated.append(round(clipped, 1))
    return calibrated

def generate_objective_answers():
    """随机生成3个客观题的答案（0或1），模拟正确/错误。此处使正确率约为60%"""
    return [1 if random.random() < 0.6 else 0 for _ in range(3)]

def main():
    np.random.seed(42)
    random.seed(42)
    data = []
    for uid in range(1, 201):
        answers = generate_answers()
        X = compute_scores(answers)                 # 理论分（整数）
        Y_calibrated = generate_calibrated_scores(X) # 校准分（浮点数，与X同范围）
        obj_answers = generate_objective_answers()  # 客观题正确标记
        row = [uid] + X + answers + Y_calibrated + obj_answers
        data.append(row)
    
    columns = (['user_id'] +
               [f'x{i}' for i in range(1,8)] +
               [f'q{i}' for i in range(1,41)] +
               [f'self_d{i}' for i in range(1,8)] +   # 注意：这里存储的是校准后的理论分，不是1-10自评分
               ['obj1', 'obj2', 'obj3'])
    df = pd.DataFrame(data, columns=columns)
    df.to_csv('data/training_data.csv', index=False)
    print("模拟数据已生成: data/training_data.csv (200行)")
    print("注意：self_d1~self_d7 现在是校准后的理论分（与x同量纲），可直接作为训练目标Y。")

if __name__ == '__main__':
    main()