def compute_X_from_answers(row):
    """如果 CSV 中没有 x1~x7 列，则根据 q1~q40 计算理论原始分 X"""
    X = np.zeros(7, dtype=int)
    for i in range(1, 41):
        ans = row[f'q{i}']
        opt_idx = ord(ans) - ord('A')
        scores = SCORES_TABLE[i-1][opt_idx]
        X += scores
    return X

def main():
    # 读取训练数据（必须包含 self_d1~self_d7, obj1~obj3 列）
    df = pd.read_csv('data/training_data.csv')
    
    # 提取 X：优先使用已有的 x1~x7 列，否则从 q1~q40 计算
    if all(col in df.columns for col in ['x1','x2','x3','x4','x5','x6','x7']):
        X = df[['x1','x2','x3','x4','x5','x6','x7']].values
    else:
        X_list = []
        for _, row in df.iterrows():
            X_list.append(compute_X_from_answers(row))
        X = np.array(X_list)
    
    # 提取 Y：校准后的理论分（由 generate_mock_data.py 生成，与 X 同量纲，可能为浮点数）
    Y = df[['self_d1','self_d2','self_d3','self_d4','self_d5','self_d6','self_d7']].values
    
    # 有效性筛选：客观题至少答对 1 题（可根据需要调整阈值）
    df['obj_score'] = df['obj1'] + df['obj2'] + df['obj3']
    valid_mask = df['obj_score'] >= 1
    X = X[valid_mask]
    Y = Y[valid_mask]
    print(f"有效样本数: {len(X)} / {len(df)}")
    
    # 标准化 X
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X)
    
    # 训练 7 个岭回归模型（每个维度一个）
    models = []
    for i in range(7):
        model = Ridge(alpha=1.0)
        model.fit(X_scaled, Y[:, i])
        models.append(model)
    
    # 保存模型和标准化器
    with open('calibration_models.pkl', 'wb') as f:
        pickle.dump({'models': models, 'scaler': scaler}, f)
    print("训练完成，模型已保存为 calibration_models.pkl")
    print("注意：Y（校准目标）与 X 同量纲，因此经验雷达图分数将与理论雷达图在同一数值范围内。")

if __name__ == '__main__':
    main()